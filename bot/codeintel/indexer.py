"""Building and updating the index: which files, what changed, parse, store, resolve imports, map tests.

Which files: in a git work tree, `git ls-files --cached --others --exclude-standard` (so .gitignore'd files never
enter); otherwise a walk that honours the root .gitignore in a simple way. Vendored and generated code is skipped
either way (node_modules, vendor, dist, build, *.min.js, *_pb2.py, files that say they are generated).

Incremental: a file is re-read only when its size or mtime changed, and re-parsed only when its content hash did.
"""

from __future__ import annotations

import fnmatch
import hashlib
import json
import os
import re
import sqlite3
import subprocess
import time
from pathlib import Path, PurePosixPath
from typing import Optional

from bot.codeintel import parsers, store

MAX_FILE_BYTES = 1_000_000
MAX_FILES = 40_000
BUILD_BUDGET_S = 180.0

SKIP_SEGMENTS = frozenset({
    ".git", ".hg", ".svn", "node_modules", "__pycache__", ".venv", "venv", "env", ".tox", ".mypy_cache", ".pytest_cache",
    ".ruff_cache", "target", "dist", "build", "vendor", "site-packages", "third_party", "bower_components", ".next",
    ".nuxt", "coverage", "htmlcov", ".eggs", ".idea", ".vscode", "out", "__generated__", "generated"})
_GENERATED_NAME = re.compile(r"(\.min\.(js|css)|_pb2(_grpc)?\.pyi?|\.pb\.go|\.generated\.\w+|\.g\.dart|-lock\.json|\.bundle\.js)$", re.I)
_GENERATED_HEAD = re.compile(rb"@generated|DO NOT EDIT|auto-?generated|Code generated by", re.I)
_TEST_DIRS = frozenset({"tests", "test", "__tests__", "spec", "specs", "testing"})
_TEST_NAME = re.compile(r"(^test_.*\.py$|_test\.(py|go|rs|rb|php)$|\.(test|spec)\.(js|jsx|ts|tsx|mjs|cjs)$|Tests?\.(java|kt|cs|swift)$|^test_.*\.rs$)")


def is_test_path(path: str) -> bool:
    parts = path.split("/")
    return any(p in _TEST_DIRS for p in parts[:-1]) or bool(_TEST_NAME.search(parts[-1]))


def module_of(path: str) -> str:
    """Dotted module name of a file: bot/a/b.py -> bot.a.b, bot/a/__init__.py -> bot.a, src/x.ts -> src.x."""
    stem = str(PurePosixPath(path).with_suffix(""))
    parts = [p for p in stem.split("/") if p]
    if parts and parts[-1] == "__init__":
        parts.pop()
    return ".".join(parts)


# ---------------------------------------------------------------- listing
def _git_files(root: Path) -> Optional[list[str]]:
    try:
        proc = subprocess.run(["git", "-C", str(root), "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
                              capture_output=True, timeout=30, check=False,
                              creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
    except (OSError, subprocess.SubprocessError):
        return None
    if proc.returncode != 0:
        return None
    return [p for p in proc.stdout.decode("utf-8", errors="replace").split("\0") if p]


def _gitignore_rules(root: Path) -> list[tuple[str, bool]]:
    rules: list[tuple[str, bool]] = []
    try:
        for raw in (root / ".gitignore").read_text(encoding="utf-8", errors="replace").splitlines():
            line = raw.strip()
            if not line or line.startswith(("#", "!")):
                continue
            rules.append((line.rstrip("/").lstrip("/"), line.endswith("/")))
    except OSError:
        pass
    return rules


def _ignored(rel: str, rules: list[tuple[str, bool]]) -> bool:
    parts = rel.split("/")
    for pattern, dir_only in rules:
        if "/" in pattern:
            if fnmatch.fnmatch(rel, pattern) or fnmatch.fnmatch(rel, pattern + "/*"):
                return True
            continue
        scope = parts[:-1] if dir_only else parts
        if any(fnmatch.fnmatch(p, pattern) for p in scope):
            return True
    return False


def _walk_files(root: Path) -> list[str]:
    rules = _gitignore_rules(root)
    out: list[str] = []
    for dirpath, dirnames, filenames in os.walk(root):
        rel_dir = Path(dirpath).relative_to(root).as_posix()
        rel_dir = "" if rel_dir == "." else rel_dir
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_SEGMENTS and not d.startswith(".")
                             and not _ignored((rel_dir + "/" + d).lstrip("/"), rules))
        for name in sorted(filenames):
            rel = (rel_dir + "/" + name).lstrip("/")
            if not _ignored(rel, rules):
                out.append(rel)
            if len(out) >= MAX_FILES * 4:
                return out
    return out


def candidate_files(root: Path) -> list[str]:
    """Repository-relative source files worth indexing, sorted."""
    suffixes = parsers.source_suffixes()
    listed = _git_files(root)
    if listed is None:
        listed = _walk_files(root)
    out = []
    for rel in listed:
        parts = rel.split("/")
        if any(p in SKIP_SEGMENTS or p.startswith(".") for p in parts[:-1]):
            continue
        name = parts[-1]
        if os.path.splitext(name)[1].lower() not in suffixes or _GENERATED_NAME.search(name):
            continue
        out.append(rel)
    out.sort()
    return out[:MAX_FILES]


# ---------------------------------------------------------------- import resolution
_JS_EXT = (".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", "/index.ts", "/index.tsx", "/index.js", "/index.jsx")


class _Resolver:
    def __init__(self, paths: list[str]):
        self.paths = set(paths)
        self.mod: dict[str, str] = {}
        self.suffix: dict[str, Optional[str]] = {}
        for p in paths:
            if not p.endswith((".py", ".pyi")):
                continue
            m = module_of(p)
            if not m:
                continue
            self.mod.setdefault(m, p)
            parts = m.split(".")
            if parts[0] in ("src", "lib", "python") and len(parts) > 1:
                self.mod.setdefault(".".join(parts[1:]), p)
            for i in range(1, len(parts)):
                key = ".".join(parts[i:])
                self.suffix[key] = None if key in self.suffix and self.suffix[key] != p else p

    def _py(self, file: str, module: str, name: str, level: int) -> Optional[str]:
        if level:
            pkg = file.split("/")[:-1]
            if level > 1:
                pkg = pkg[: len(pkg) - (level - 1)] if len(pkg) >= level - 1 else []
            base = ".".join(pkg + ([module] if module else []))
        else:
            base = module
        tries = []
        if name and name != "*":
            tries.append(f"{base}.{name}" if base else name)
        if base:
            tries.append(base)
            parts = base.split(".")
            tries += [".".join(parts[:i]) for i in range(len(parts) - 1, 0, -1)]
        for t in tries:
            if t in self.mod:
                return self.mod[t]
        if not level:
            for t in tries:
                hit = self.suffix.get(t)
                if hit:
                    return hit
        return None

    def _js(self, file: str, module: str) -> Optional[str]:
        if not module.startswith("."):
            return None
        base = PurePosixPath(file).parent
        target = os.path.normpath(str(base / module)).replace("\\", "/")
        if target in self.paths:
            return target
        for ext in _JS_EXT:
            if target + ext in self.paths:
                return target + ext
        return None

    def resolve(self, file: str, module: str, name: str, level: int) -> Optional[str]:
        if file.endswith((".py", ".pyi")):
            hit = self._py(file, module, name, level)
        else:
            hit = self._js(file, module)
        return hit if hit != file else None


# ---------------------------------------------------------------- the update
def _decode(raw: bytes) -> str:
    return raw.decode("utf-8", errors="replace")


def _store_file(conn: sqlite3.Connection, rel: str, st, raw: bytes, digest: str, ids_from: int, existed: bool) -> Optional[int]:
    """Parse one file and replace its rows. Returns the number of symbols stored, or None when the file is not
    indexable (binary, generated). Symbol ids are `ids_from` upward."""
    if b"\x00" in raw[:4096] or _GENERATED_HEAD.search(raw[:400]):
        if existed:
            _drop_file(conn, rel)
        return None
    source = _decode(raw)
    suffix = os.path.splitext(rel)[1].lower()
    parsed = parsers.parse_source(suffix, source)
    if existed:
        _drop_file(conn, rel)
    module = module_of(rel)
    lines = source.count("\n") + 1
    conn.execute("INSERT INTO ci_files VALUES (?,?,?,?,?,?,?,?,?)",
                 (rel, parsed.lang if parsed else "", module, st.st_size, st.st_mtime_ns, digest, lines,
                  1 if is_test_path(rel) else 0, parsed.parser if parsed else "none"))
    if parsed is None:
        return 0
    ids = [ids_from + n for n in range(len(parsed.symbols))]
    depths: list[int] = []
    sym_rows = []
    fts_rows = []
    for n, sym in enumerate(parsed.symbols):
        parent_id = ids[sym.parent] if 0 <= sym.parent < n else None
        depth = depths[sym.parent] + 1 if 0 <= sym.parent < n else 0
        depths.append(depth)
        sym_rows.append((ids[n], rel, sym.kind, sym.name, sym.qname, f"{module}.{sym.qname}" if module else sym.qname,
                         sym.signature, sym.doc, sym.decorators, sym.start, sym.end, parent_id, depth))
        fts_rows.append((ids[n], sym.name, _split_words(sym.name), sym.qname, sym.doc))
    conn.executemany("INSERT INTO ci_symbols (id, file, kind, name, qname, fq, signature, doc, decorators, start_line,"
                     " end_line, parent_id, depth) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)", sym_rows)
    conn.executemany("INSERT INTO ci_symfts (rowid, name, parts, qname, doc) VALUES (?,?,?,?,?)", fts_rows)
    conn.executemany("INSERT INTO ci_refs VALUES (?,?,?,?,?)",
                     [(r.name, rel, r.line, ids[r.sym] if 0 <= r.sym < len(ids) else None, r.kind) for r in parsed.refs])
    conn.executemany("INSERT INTO ci_imports (file, module, name, level, line, resolved) VALUES (?,?,?,?,?,NULL)",
                     [(rel, i.module, i.name, i.level, i.line) for i in parsed.imports])
    return len(parsed.symbols)


_CAMEL = re.compile(r"(?<=[a-z0-9])(?=[A-Z])")


def _split_words(name: str) -> str:
    words = []
    for piece in re.split(r"_+", name):
        words.extend(p.lower() for p in _CAMEL.split(piece) if p)
    return " ".join(words) if len(words) > 1 else ""


def _drop_file(conn: sqlite3.Connection, rel: str) -> None:
    conn.execute("DELETE FROM ci_symfts WHERE rowid IN (SELECT id FROM ci_symbols WHERE file=?)", (rel,))
    for table, col in (("ci_symbols", "file"), ("ci_refs", "file"), ("ci_imports", "file"), ("ci_files", "path")):
        conn.execute(f"DELETE FROM {table} WHERE {col}=?", (rel,))


def _resolve_imports(conn: sqlite3.Connection) -> None:
    paths = [r["path"] for r in conn.execute("SELECT path FROM ci_files")]
    resolver = _Resolver(paths)
    rows = conn.execute("SELECT rowid, file, module, name, level FROM ci_imports").fetchall()
    conn.executemany("UPDATE ci_imports SET resolved=? WHERE rowid=?",
                     [(resolver.resolve(r["file"], r["module"], r["name"], r["level"]), r["rowid"]) for r in rows])




def _test_stems(name: str) -> list[str]:
    """Names a test file's subject may carry: test_repo_map.py -> repo_map; foo.test.ts -> foo; foo_test.go -> foo."""
    stem = name.rsplit(".", 1)[0] if "." in name else name
    for suffix in (".test", ".spec"):
        if stem.endswith(suffix):
            stem = stem[: -len(suffix)]
    out = []
    if stem.startswith("test_"):
        out.append(stem[5:])
    for tail in ("_test", "_tests", "Test", "Tests"):
        if stem.endswith(tail) and len(stem) > len(tail):
            out.append(stem[: -len(tail)])
    if stem != name.rsplit(".", 1)[0] or not out:
        out.append(stem)
    return [s for s in dict.fromkeys(out) if s]


def _rebuild_testmap(conn: sqlite3.Connection, keep_coverage: bool = True) -> None:
    conn.execute("DELETE FROM ci_testmap WHERE how != 'coverage'" if keep_coverage else "DELETE FROM ci_testmap")
    # imports: a test file imports a (non-test) source file
    conn.execute(
        "INSERT INTO ci_testmap SELECT DISTINCT i.file, NULL, i.resolved, 'import', 3 FROM ci_imports i "
        "JOIN ci_files t ON t.path = i.file AND t.is_test = 1 JOIN ci_files s ON s.path = i.resolved AND s.is_test = 0 "
        "WHERE i.resolved IS NOT NULL")
    # references: a test function mentions a symbol defined in a source file that the test file imports
    defined: dict[str, set[str]] = {}
    for r in conn.execute("SELECT file, name FROM ci_symbols WHERE length(name) > 2 AND file IN (SELECT path FROM ci_files WHERE is_test = 0)"):
        defined.setdefault(r["file"], set()).add(r["name"])
    imported: dict[str, set[str]] = {}
    for r in conn.execute("SELECT DISTINCT i.file, i.resolved FROM ci_imports i JOIN ci_files t ON t.path = i.file AND t.is_test = 1 "
                          "WHERE i.resolved IS NOT NULL"):
        if r["resolved"] in defined:
            imported.setdefault(r["file"], set()).add(r["resolved"])
    seen_rows = set()
    for r in conn.execute("SELECT DISTINCT r.file, r.name, e.qname FROM ci_refs r JOIN ci_symbols e ON e.id = r.sym_id "
                          "WHERE e.kind IN ('function', 'method') AND r.file IN (SELECT path FROM ci_files WHERE is_test = 1)"):
        for src in imported.get(r["file"], ()):
            if r["name"] in defined[src] and src != r["file"]:
                seen_rows.add((r["file"], r["qname"], src, "ref", 4))
    conn.executemany("INSERT INTO ci_testmap VALUES (?,?,?,?,?)", sorted(seen_rows))
    # naming: test_x.py / x_test.go / x.test.ts test x.*
    stems: dict[str, list[str]] = {}
    for r in conn.execute("SELECT path FROM ci_files WHERE is_test = 0"):
        stem = r["path"].rsplit("/", 1)[-1].rsplit(".", 1)[0]
        stems.setdefault(stem, []).append(r["path"])
    rows = []
    for r in conn.execute("SELECT path FROM ci_files WHERE is_test = 1"):
        name = r["path"].rsplit("/", 1)[-1]
        for stem in _test_stems(name):
            for src in stems.get(stem, []):
                rows.append((r["path"], None, src, "name", 1))
    conn.executemany("INSERT INTO ci_testmap VALUES (?,?,?,?,?)", rows)


def _load_coverage(conn: sqlite3.Connection, root: Path) -> None:
    """Optional: per-test coverage from `coverage json --show-contexts` (coverage.json) when present."""
    cov = root / "coverage.json"
    stamp = ""
    if cov.is_file():
        st = cov.stat()
        stamp = f"{st.st_mtime_ns}:{st.st_size}"
    if stamp == store.meta(conn, "coverage_stamp"):
        return
    conn.execute("DELETE FROM ci_testmap WHERE how = 'coverage'")
    rows = set()
    if stamp:
        try:
            data = json.loads(cov.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            data = {}
        known = {r["path"] for r in conn.execute("SELECT path FROM ci_files")}
        for fname, info in (data.get("files") or {}).items():
            src = fname.replace("\\", "/")
            try:
                src = Path(fname).resolve().relative_to(root).as_posix() if os.path.isabs(fname) else src
            except ValueError:
                continue
            if src not in known:
                continue
            for contexts in (info.get("contexts") or {}).values():
                for ctx in contexts:
                    ctx = str(ctx).split("|")[0].strip()
                    if "::" not in ctx:
                        continue
                    tfile, _, tname = ctx.partition("::")
                    tfile = tfile.replace("\\", "/")
                    if tfile != src and tfile in known:
                        rows.add((tfile, tname.replace("::", "."), src, "coverage", 5))
    conn.executemany("INSERT INTO ci_testmap VALUES (?,?,?,?,?)", sorted(rows))
    store.set_meta(conn, "coverage_stamp", stamp)


def update(root: Path, *, force: bool = False, only: Optional[list[str]] = None, chunks: bool = False) -> dict:
    """Bring the index up to date with the files on disk and return what happened.

    `only` limits the work to those repository-relative files (a fast path after an edit); `force` re-parses
    everything; `chunks` also refreshes code_search's text chunks (and nothing else of theirs).
    """
    root = Path(root).resolve()
    started = time.monotonic()
    stats = {"files": 0, "indexed": 0, "unchanged": 0, "removed": 0, "skipped": 0, "complete": True}
    with store.write_lock(root):
        conn = store.connect(root)
        try:
            known = {r["path"]: (r["mtime_ns"], r["size"], r["hash"]) for r in conn.execute("SELECT path, mtime_ns, size, hash FROM ci_files")}
            if only is not None:
                wanted = [p for p in dict.fromkeys(x.replace("\\", "/").removeprefix("./") for x in only)
                          if os.path.splitext(p)[1].lower() in parsers.source_suffixes()]
                listing = wanted
            else:
                listing = candidate_files(root)
            next_id = conn.execute("SELECT COALESCE(MAX(id), 0) + 1 FROM ci_symbols").fetchone()[0]
            deadline = started + BUILD_BUDGET_S
            seen: set[str] = set()
            changed = False
            for rel in listing:
                if time.monotonic() > deadline:
                    stats["complete"] = False
                    break
                try:
                    st = (root / rel).stat()
                except OSError:
                    continue
                if not (root / rel).is_file() or st.st_size > MAX_FILE_BYTES or st.st_size == 0:
                    stats["skipped"] += 1
                    continue
                seen.add(rel)
                old = known.get(rel)
                if old and not force and old[0] == st.st_mtime_ns and old[1] == st.st_size:
                    stats["unchanged"] += 1
                    continue
                try:
                    raw = (root / rel).read_bytes()
                except OSError:
                    continue
                digest = hashlib.blake2b(raw, digest_size=16).hexdigest()
                if old and not force and old[2] == digest:
                    conn.execute("UPDATE ci_files SET mtime_ns=?, size=? WHERE path=?", (st.st_mtime_ns, st.st_size, rel))
                    stats["unchanged"] += 1
                    continue
                used = _store_file(conn, rel, st, raw, digest, next_id, old is not None)
                if used is not None:
                    next_id += used
                    stats["indexed"] += 1
                    changed = True
                else:
                    stats["skipped"] += 1
                    seen.discard(rel)
                    changed = changed or rel in known
            if only is None and stats["complete"]:
                for rel in set(known) - seen:
                    _drop_file(conn, rel)
                    stats["removed"] += 1
                    changed = True
            elif only is not None:
                for rel in listing:
                    if rel in known and not (root / rel).is_file():
                        _drop_file(conn, rel)
                        stats["removed"] += 1
                        changed = True
            if changed or force or store.meta(conn, "resolved") != "1":
                _resolve_imports(conn)
                _rebuild_testmap(conn)
                store.set_meta(conn, "resolved", "1")
            _load_coverage(conn, root)
            store.set_meta(conn, "updated", str(time.time()))
            conn.commit()
            stats["files"] = conn.execute("SELECT COUNT(*) FROM ci_files").fetchone()[0]
            stats["symbols"] = conn.execute("SELECT COUNT(*) FROM ci_symbols").fetchone()[0]
        finally:
            conn.close()
    if chunks:
        try:
            from bot.agent_runtime import search_index

            search_index.refresh_code_index(root)
        except Exception:  # noqa: BLE001 - the text chunks are a bonus; the symbol index stands without them
            stats["chunks_error"] = True
    stats["seconds"] = round(time.monotonic() - started, 3)
    return stats
